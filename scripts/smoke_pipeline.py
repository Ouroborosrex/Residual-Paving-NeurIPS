"""Exercise all training stages on a tiny random CPU model and synthetic prompts.

This is a software check, not a reproduction of the paper's behavioral results.
No pretrained weights or benchmark data are downloaded.
"""
from __future__ import annotations

import csv
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import time

os.environ["CUDA_VISIBLE_DEVICES"] = ""
os.environ.setdefault("OMP_NUM_THREADS", "2")
os.environ.setdefault("MKL_NUM_THREADS", "2")

import torch
from tokenizers import Tokenizer
from tokenizers.models import WordLevel
from tokenizers.pre_tokenizers import Whitespace
from transformers import PreTrainedTokenizerFast, Qwen2Config, Qwen2ForCausalLM

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    torch.set_num_threads(2)
    torch.manual_seed(42)
    started = time.monotonic()
    with tempfile.TemporaryDirectory(prefix="rp_pipeline_") as directory:
        work = Path(directory)
        model_path = work / "tiny_model"
        words = ["[PAD]", "[EOS]", "[UNK]", "user", "assistant", ":", "edit",
                 "benign", "keep", "sample", "safe", "answer", "test", ".", "0",
                 "1", "2", "3", "4", "5", "6", "7"]
        tokenizer_backend = Tokenizer(WordLevel({word: i for i, word in enumerate(words)}, unk_token="[UNK]"))
        tokenizer_backend.pre_tokenizer = Whitespace()
        tokenizer = PreTrainedTokenizerFast(tokenizer_object=tokenizer_backend,
                                           pad_token="[PAD]", eos_token="[EOS]", unk_token="[UNK]")
        tokenizer.chat_template = "{% for message in messages %}{{ message['role'] + ': ' + message['content'] + '\\n' }}{% endfor %}{% if add_generation_prompt %}assistant: {% endif %}"
        tokenizer.save_pretrained(model_path)
        model = Qwen2ForCausalLM(Qwen2Config(vocab_size=len(words), hidden_size=32,
            intermediate_size=64, num_hidden_layers=6, num_attention_heads=4,
            num_key_value_heads=2, max_position_embeddings=2048,
            pad_token_id=0, eos_token_id=1))
        model.save_pretrained(model_path)
        del model
        for bucket in ["edit", "benign"]:
            rows = [{"instruction": f"{bucket} sample {i} test."} for i in range(8)]
            (work / f"{bucket}.json").write_text(json.dumps(rows))
        with (work / "keep.csv").open("w", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=["Behavior"])
            writer.writeheader()
            writer.writerows({"Behavior": f"keep sample {i} test."} for i in range(8))
        env = dict(os.environ, RP_SALAD_PATH=str(work / "edit.json"),
                   RP_ALPACA_PATH=str(work / "benign.json"), RP_HARMBENCH_PATH=str(work / "keep.csv"),
                   HF_HUB_OFFLINE="1", TRANSFORMERS_OFFLINE="1")
        command = [sys.executable, str(ROOT / "experiments/moe_gate_policy_smoke.py"),
            "--model-id", str(model_path), "--n", "4", "--eval-fraction", "0.5",
            "--router-layer-spec", "1,2", "--intervention-layer-spec", "auto",
            "--moe-num-experts", "3", "--moe-bottleneck-dim", "8", "--router-hidden-dim", "8",
            "--gate-pretrain-epochs", "1", "--contrastive-epochs", "1",
            "--stage1-epochs", "1", "--stage2-epochs", "1", "--stage3-epochs", "1",
            "--steer-steps", "4", "--stage1-train-steps", "2", "--stage2-train-steps", "4",
            "--trace-batch-size", "1", "--build-batch-size", "1", "--eval-max-new-tokens", "4",
            "--edit-target-mode", "safe_reframe", "--edit-anchor-prefix", "safe answer",
            "--harmful-veto", "--harmful-veto-l2-weight", "0.1",
            "--harmful-veto-threshold-tie-break", "high",
            "--example-cache-dir", str(work / "cache")]
        result = subprocess.run(command, cwd=ROOT, env=env, text=True, capture_output=True)
        if result.returncode:
            print(result.stdout)
            print(result.stderr, file=sys.stderr)
            raise SystemExit(result.returncode)
        match = re.search(r"MoE gate-policy smoke run: (.+)", result.stdout)
        if not match:
            raise RuntimeError("Training completed without a run-directory receipt.")
        run = Path(match[1].strip())
        summary = json.loads((run / "summary.json").read_text())
        assert summary["status"] == "ok", summary.get("status")
        checkpoint = run / "moe_gate_policy_smoke/checkpoint.pt"
        # This is the checkpoint generated by the subprocess above.
        payload = torch.load(checkpoint, map_location="cpu", weights_only=False)
        assert {"moe_router_state_dict", "moe_controller_state_dict", "config"} <= payload.keys()
        assert all(torch.isfinite(x).all().item() for x in payload["moe_controller_state_dict"].values())
        # Exercise both public checkpoint consumers while the temporary data and
        # model are still available. All completion content remains temporary.
        for entry, extra in [
            ("moe_checkpoint_reeval", ["--skip-scale-calibration", "--eval-path",
                                        "learned:thresholded_soft:router:selected"]),
            ("moe_export_completions", ["--buckets", "benign_keep", "--eval-path",
                                        "learned:thresholded_soft:router:1"]),
        ]:
            output = work / entry
            check = subprocess.run([sys.executable, str(ROOT / f"experiments/{entry}.py"),
                "--checkpoint", str(checkpoint), "--output-dir", str(output), *extra],
                cwd=ROOT, env=env, text=True, capture_output=True)
            if check.returncode:
                print(check.stdout)
                print(check.stderr, file=sys.stderr)
                raise SystemExit(check.returncode)
            checked_summary = json.loads((output / "summary.json").read_text())
            assert checked_summary["status"] == "ok", checked_summary.get("status")
        exported = json.loads((work / "moe_export_completions/completions/learned_all.json").read_text())
        assert len(exported["rows"]) == 2
        report = {"status": "passed", "device": "cpu", "model": "tiny random Qwen2",
                  "downloaded_pretrained_weights": False, "benchmark_data": False,
                  "stages": ["target/cache construction", "gate pretraining", "contrastive warmup",
                             "forced-edit fitting", "joint fitting", "gate/veto calibration",
                             "checkpoint serialization", "policy evaluation",
                             "checkpoint re-evaluation", "completion export"],
                  "elapsed_seconds": round(time.monotonic() - started, 2),
                  "checkpoint_keys": sorted(payload),
                  "interpretation": "Software execution check only; no behavioral or safety claim."}
        out = ROOT / "results/repro/tiny_pipeline.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(report, indent=2) + "\n")
        print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
